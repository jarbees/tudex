private val ITF_PATTERNS = mapOf(
    '0' to "nnwwn",
    '1' to "wnnnw",
    '2' to "nwnnw",
    '3' to "wwnnn",
    '4' to "nnwnw",
    '5' to "wnwnn",
    '6' to "nwwnn",
    '7' to "nnnww",
    '8' to "wnnwn",
    '9' to "nwnwn"
)

private fun encodeInterleaved25(data: String): List<Int>? {
    if (data.length % 2 == 1) return null
    if (!data.all { it.isDigit() }) return null

    val widths = mutableListOf<Int>()

    widths += listOf(1, 1, 1, 1) // start

    for (i in data.indices step 2) {
        val bars = ITF_PATTERNS[data[i]]!!
        val spaces = ITF_PATTERNS[data[i + 1]]!!

        repeat(5) { j ->
            widths += if (bars[j] == 'w') 3 else 1
            widths += if (spaces[j] == 'w') 3 else 1
        }
    }

    widths += listOf(3, 1, 1) // stop
    return widths
}

private fun renderBarcodeArgb(
    barWidths: List<Int>,
    height: Int,
    scale: Int = 1
): IntArray {
    val width = barWidths.sum() * scale
    val pixels = IntArray(width * height) { 0x00000000.toInt() }

    var x = 0
    var isBar = true

    for (w in barWidths) {
        val pxWidth = w * scale
        if (isBar) {
            repeat(pxWidth) { dx ->
                repeat(height) { y ->
                    //pixels[y * width + x + dx] = 0xFF000000.toInt()
                    pixels[y * width + x + dx] = 0xFF000000.toInt()
                }
            }
        }
        x += pxWidth
        isBar = !isBar
    }

    return pixels
}

private fun argbToPng(
    pixels: IntArray,
    width: Int,
    height: Int
): ByteArray {
    val bitmap = Bitmap32(width, height, pixels)
    return PNG.encode(bitmap = bitmap)
}


fun platformImageFromInterleaved25(
    data: String,
    height: Int = 100
): PlatformImage? {
    val bars = encodeInterleaved25(data) ?: return null
    val width = bars.sum()// * 2
    val pixels = renderBarcodeArgb(bars, height)
    val pngBytes = argbToPng(pixels, width, height)

    return PlatformImage(pngBytes)
}
